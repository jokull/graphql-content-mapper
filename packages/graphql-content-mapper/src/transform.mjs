// Turns GraphQL SDL into TypeScript: gql.tada's introspection type (plus the `setupSchema` augmentation, so
// `graphql()` from 'gql.tada' is typed as soon as the schema file is in the program) and a plain TypeScript type for
// every named type in the schema. Type and field names are mapped back to the SDL, so diagnostics, hover and
// go-to-definition land in the .graphql file.
import { createRequire } from 'node:module'
import { basename, extname } from 'node:path'

// graphql@16 has no "exports" map; requiring everything as CommonJS keeps one copy of the module, so the
// `instanceof` checks inside graphql-js hold for the deep import of validateSDL.
const require = createRequire(import.meta.url)
const graphql = require('graphql')
const { validateSDL } = require('graphql/validation/validate')
const { minifyIntrospection, outputIntrospectionFile } = require('@gql.tada/internal')

const SpanMapKind = { Verbatim: 0, Atom: 1, Alias: 2 }

const BUILTIN_SCALARS = {
  ID: 'string',
  String: 'string',
  Int: 'number',
  Float: 'number',
  Boolean: 'boolean',
}

const DiagnosticCode = { Syntax: 1, Validation: 2 }

class Writer {
  text = ''
  mappings = []

  write(text) {
    this.text += text
  }

  /** Writes `text`, which is identical to the SDL text at `node.loc`, and maps the two spans. */
  writeName(text, node) {
    if (node?.loc && node.loc.end - node.loc.start === text.length) {
      this.mappings.push([this.text.length, text.length, node.loc.start, text.length, SpanMapKind.Verbatim])
    }
    this.text += text
  }

  writeDoc(description, indent) {
    if (!description) return
    const lines = description.replace(/\*\//g, '*\\/').split('\n')
    this.write(`${indent}/**\n${lines.map((line) => `${indent} * ${line}`.trimEnd()).join('\n')}\n${indent} */\n`)
  }
}

function diagnosticFromError(error, code) {
  const node = error.nodes?.find((node) => node.loc)
  if (node?.loc) return { messageText: error.message, start: node.loc.start, length: node.loc.end - node.loc.start, code }
  return { messageText: error.message, start: error.positions?.[0] ?? 0, length: 1, code }
}

function empty(diagnostics = []) {
  return { text: 'export {};\n', extension: '.ts', mappings: [], diagnostics }
}

export function transformSchema(content, options = {}, fileName = '') {
  let document
  try {
    document = graphql.parse(content)
  } catch (error) {
    if (error instanceof graphql.GraphQLError) return empty([diagnosticFromError(error, DiagnosticCode.Syntax)])
    throw error
  }

  // Only schema files are mapped here; a document of operations has nothing to contribute.
  if (!document.definitions.some((definition) => graphql.isTypeSystemDefinitionNode(definition) || graphql.isTypeSystemExtensionNode(definition))) {
    return empty()
  }

  const sdlErrors = validateSDL(document)
  if (sdlErrors.length) return empty(sdlErrors.map((error) => diagnosticFromError(error, DiagnosticCode.Validation)))

  const schema = graphql.buildASTSchema(document, { assumeValidSDL: true })
  const schemaErrors = graphql.validateSchema(schema)
  if (schemaErrors.length) return empty(schemaErrors.map((error) => diagnosticFromError(error, DiagnosticCode.Validation)))

  const writer = new Writer()
  writer.write('// Generated by graphql-content-mapper from this schema. Do not edit; edit the .graphql file.\n\n')
  if (options.gqlTada !== false) {
    // A named schema (gql.tada's multi-schema setup) skips the `setupSchema` augmentation; it is passed to
    // `initGraphQLTada<{ introspection }>()` explicitly instead. Options apply to every mapped file, so
    // `named: true` takes each schema's name from its file name (dato.graphql → 'dato').
    const name = options.named ? basename(fileName, extname(fileName)) : undefined
    const introspection = { ...minifyIntrospection(graphql.introspectionFromSchema(schema)), name }
    writer.write(outputIntrospectionFile(introspection, { fileType: '.d.ts', shouldPreprocess: true }))
    writer.write('\n\n')
  }
  writePlainTypes(writer, schema, options.scalars ?? {})
  return { text: writer.text, extension: '.ts', mappings: writer.mappings, diagnostics: [] }
}

function writePlainTypes(writer, schema, customScalars) {
  const types = Object.values(schema.getTypeMap()).filter((type) => !type.name.startsWith('__'))

  writer.write('export interface Scalars {\n')
  for (const type of types) {
    if (!graphql.isScalarType(type)) continue
    writer.write('  ')
    writer.writeName(type.name, type.astNode?.name)
    writer.write(`: ${customScalars[type.name] ?? BUILTIN_SCALARS[type.name] ?? 'unknown'};\n`)
  }
  writer.write('}\n')

  for (const type of types) {
    if (graphql.isScalarType(type)) {
      // Built-in scalars stay inside Scalars so they don't shadow globals such as `String` and `Boolean`.
      if (type.name in BUILTIN_SCALARS) continue
      writer.write('\n')
      writer.writeDoc(type.description, '')
      writer.write('export type ')
      writer.writeName(type.name, type.astNode?.name)
      writer.write(` = Scalars['${type.name}'];\n`)
    } else if (graphql.isEnumType(type)) {
      writer.write('\n')
      writer.writeDoc(type.description, '')
      writer.write('export type ')
      writer.writeName(type.name, type.astNode?.name)
      writer.write(' =')
      for (const value of type.getValues()) {
        writer.write("\n  | '")
        writer.writeName(value.name, value.astNode?.name)
        writer.write("'")
      }
      writer.write(';\n')
    } else if (graphql.isUnionType(type)) {
      writer.write('\n')
      writer.writeDoc(type.description, '')
      writer.write('export type ')
      writer.writeName(type.name, type.astNode?.name)
      writer.write(` = ${type.getTypes().map((member) => member.name).join(' | ') || 'never'};\n`)
    } else if (graphql.isObjectType(type) || graphql.isInterfaceType(type) || graphql.isInputObjectType(type)) {
      writer.write('\n')
      writer.writeDoc(type.description, '')
      writer.write('export interface ')
      writer.writeName(type.name, type.astNode?.name)
      if (graphql.isObjectType(type) || graphql.isInterfaceType(type)) {
        const interfaces = type.getInterfaces().map((iface) => iface.name)
        if (interfaces.length) writer.write(` extends ${interfaces.join(', ')}`)
      }
      writer.write(' {\n')
      if (graphql.isObjectType(type)) writer.write(`  __typename: '${type.name}';\n`)
      for (const field of Object.values(type.getFields())) {
        writer.writeDoc(field.description, '  ')
        writer.write('  ')
        writer.writeName(field.name, field.astNode?.name)
        // Nullable input fields can be omitted; nullable output fields are always present, possibly as null.
        const optional = graphql.isInputObjectType(type) && !graphql.isNonNullType(field.type)
        writer.write(`${optional ? '?' : ''}: ${typeReference(field.type)};\n`)
      }
      writer.write('}\n')
    }
  }
}

function typeReference(type) {
  if (graphql.isNonNullType(type)) return nonNullReference(type.ofType)
  return `${nonNullReference(type)} | null`
}

function nonNullReference(type) {
  if (graphql.isListType(type)) return `Array<${typeReference(type.ofType)}>`
  if (graphql.isScalarType(type) && type.name in BUILTIN_SCALARS) return `Scalars['${type.name}']`
  return type.name
}
